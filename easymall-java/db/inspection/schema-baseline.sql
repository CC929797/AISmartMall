-- 阶段 0：只读数据库结构巡检。
-- 使用已授权的只读账号连接并选中目标测试库后执行。
-- 只查询 information_schema；不查询业务行、不创建/修改/删除对象。
-- DATABASE() 为 NULL 时结果为空，先在客户端明确选中目标库。
-- 目标为 MySQL 8；CHECK_CONSTRAINTS 需服务器支持相应元数据视图。
-- 导出结果仍需人工脱敏后才可提交，不在脚本中填写连接凭据。

-- 1. 当前库的字符集与排序规则。
SELECT SCHEMA_NAME, DEFAULT_CHARACTER_SET_NAME, DEFAULT_COLLATION_NAME
FROM information_schema.SCHEMATA
WHERE SCHEMA_NAME = DATABASE();

-- 2. 表和视图的结构属性，不读取 TABLE_ROWS 等业务数据量信息。
SELECT TABLE_NAME, TABLE_TYPE, ENGINE, TABLE_COLLATION, TABLE_COMMENT
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME;

-- 3. 字段类型、长度、精度、默认值、空值与生成属性。
SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME,
       DATA_TYPE, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT,
       CHARACTER_MAXIMUM_LENGTH, CHARACTER_OCTET_LENGTH,
       NUMERIC_PRECISION, NUMERIC_SCALE, DATETIME_PRECISION,
       CHARACTER_SET_NAME, COLLATION_NAME, EXTRA,
       GENERATION_EXPRESSION, COLUMN_COMMENT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- 4. 索引与索引列顺序；NON_UNIQUE=0 表示唯一索引。
-- 不查询 CARDINALITY，避免把估算值当作结构或业务验收证据。
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX,
       COLUMN_NAME, COLLATION, SUB_PART, NULLABLE,
       INDEX_TYPE, INDEX_COMMENT
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;

-- 5. 主键、唯一键、外键和检查约束清单。
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE
FROM information_schema.TABLE_CONSTRAINTS
WHERE CONSTRAINT_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;

-- 6. 约束涉及的字段及其顺序，同时列出外键引用目标。
SELECT TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, ORDINAL_POSITION,
       POSITION_IN_UNIQUE_CONSTRAINT,
       REFERENCED_TABLE_SCHEMA, REFERENCED_TABLE_NAME,
       REFERENCED_COLUMN_NAME
FROM information_schema.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION;

-- 7. 外键引用规则。
SELECT TABLE_NAME, CONSTRAINT_NAME,
       UNIQUE_CONSTRAINT_SCHEMA, UNIQUE_CONSTRAINT_NAME,
       REFERENCED_TABLE_NAME, MATCH_OPTION, UPDATE_RULE, DELETE_RULE
FROM information_schema.REFERENTIAL_CONSTRAINTS
WHERE CONSTRAINT_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, CONSTRAINT_NAME;

-- 8. 检查约束表达式；仅在服务器提供 CHECK_CONSTRAINTS 时运行。
SELECT tc.TABLE_NAME, tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE
FROM information_schema.TABLE_CONSTRAINTS AS tc
JOIN information_schema.CHECK_CONSTRAINTS AS cc
  ON cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA
 AND cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_SCHEMA = DATABASE()
  AND tc.CONSTRAINT_TYPE = 'CHECK'
ORDER BY tc.TABLE_NAME, tc.CONSTRAINT_NAME;
